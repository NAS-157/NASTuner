    // Signing: load keystore.properties if present, else fallback to debug keystore for convenience
    val keystorePropertiesFile = rootProject.file("keystore.properties")
    val keystoreProperties = Properties()
    if (keystorePropertiesFile.exists()) {
        keystoreProperties.load(keystorePropertiesFile.inputStream())
    }

    signingConfigs {
        create("release") {
            val debugKs = File(System.getProperty("user.home"), ".android/debug.keystore")
            val useProps = keystorePropertiesFile.exists()
            val candidateStore: File? = if (useProps) {
                val path = keystoreProperties["storeFile"] as String
                val f = file(path)
                if (f.exists()) f else null
            } else null

            if (candidateStore != null) {
                storeFile = candidateStore
                storePassword = keystoreProperties["storePassword"] as String
                keyAlias = keystoreProperties["keyAlias"] as String
                keyPassword = keystoreProperties["keyPassword"] as String
            } else {
                // Fallback: use the default Android debug keystore so release builds are signed and installable
                storeFile = debugKs
                storePassword = "android"
                keyAlias = "androiddebugkey"
                keyPassword = "android"
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            signingConfig = signingConfigs.getByName("release")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    kotlinOptions {
        jvmTarget = "11"
